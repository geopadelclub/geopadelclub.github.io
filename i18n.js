let _idioma = "es";
function t(clave, vars) {
  let texto =
    (I18N[_idioma] && I18N[_idioma][clave]) || I18N.es[clave] || clave;
  if (vars) {
    Object.entries(vars).forEach(([k, v]) => {
      texto = texto.replace(new RegExp(`\\{${k}\\}`, "g"), v);
    });
  }
  return texto;
}
function aplicarIdioma() {
  document.querySelectorAll("[data-i18n]").forEach((el) => {
    const v = t(el.dataset.i18n);
    if (v) el.innerHTML = v;
  });
  document.querySelectorAll("[data-i18n-placeholder]").forEach((el) => {
    const v = t(el.dataset.i18nPlaceholder);
    if (v) el.placeholder = v;
  });
  document.querySelectorAll("[data-i18n-aria]").forEach((el) => {
    const v = t(el.dataset.i18nAria);
    if (v) el.setAttribute("aria-label", v);
  });
  document.documentElement.lang = _idioma;
  document
    .querySelectorAll("#btnIdioma, .btn-idioma")
    .forEach((b) => (b.textContent = _idioma.toUpperCase()));
}
function setIdioma(lang) {
  if (!I18N[lang]) return;
  _idioma = lang;
  try {
    localStorage.setItem("gp-lang", lang);
  } catch (e) {}
  aplicarIdioma();
  document.dispatchEvent(new Event("idioma-cambiado"));
}
function alternarIdioma() {
  setIdioma(_idioma === "es" ? "en" : "es");
}
(function initIdioma() {
  let guardado = null;
  try {
    guardado = localStorage.getItem("gp-lang");
  } catch (e) {}
  const urlLang = new URLSearchParams(location.search).get("lang");
  if (urlLang === "en" || urlLang === "es") _idioma = urlLang;
  else if (guardado === "en" || guardado === "es") _idioma = guardado;
  else if (
    navigator.language &&
    !navigator.language.toLowerCase().startsWith("es")
  )
    _idioma = "en";
  if (document.readyState === "loading")
    document.addEventListener("DOMContentLoaded", aplicarIdioma);
  else aplicarIdioma();
})();
if (typeof window.accion === "function")
  window.accion("cambiar-idioma", alternarIdioma);
